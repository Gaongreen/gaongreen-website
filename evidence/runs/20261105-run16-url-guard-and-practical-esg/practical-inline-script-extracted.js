function setLanguage(lang) {
  const dict = copy[lang] || copy.en;
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";

  document.querySelectorAll("[data-i18n]").forEach(function (el) {
    const key = el.getAttribute("data-i18n");
    if (Object.prototype.hasOwnProperty.call(dict, key)) el.textContent = dict[key];
  });

  document.querySelectorAll("[data-lang]").forEach(function (button) {
    const selected = button.getAttribute("data-lang") === lang;
    button.classList.toggle("active", selected);
    button.setAttribute("aria-pressed", selected ? "true" : "false");
  });

  document.title = lang === "ko"
    ? "가온그린 | 중소기업을 위한 실용적인 ESG"
    : lang === "ar"
      ? "GaonGreen | حلول ESG عملية"
      : "GaonGreen | Practical ESG for SMEs";

  try { localStorage.setItem("gaongreen-language", lang); } catch (e) {}
}

document.addEventListener("click", function (event) {
  const button = event.target.closest("[data-lang]");
  if (button) {
    event.preventDefault();
    setLanguage(button.getAttribute("data-lang"));
  }
});

document.getElementById("year").textContent = new Date().getFullYear();

let initialLanguage = "en";
try {
  const savedLanguage = localStorage.getItem("gaongreen-language");
  if (savedLanguage && ["en", "ko", "ar"].includes(savedLanguage)) initialLanguage = savedLanguage;
} catch (e) {}
setLanguage(initialLanguage);
